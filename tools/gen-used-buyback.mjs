const DISC = 10; // −10만원
const toWon = (v) => Math.round(v * 10000);
const agg = (rows, i) => {
  const vals = rows.map((r) => r[i]).filter((v) => v != null);
  return vals.length ? [Math.min(...vals), Math.max(...vals)] : null;
};
const mkRange = (lo, hi) => {
  if (lo == null || hi == null) return null;
  let [mn, mx] = [lo - DISC, hi - DISC];
  if (mx < 1) return null;          // 최대가 1만 미만 → 매장 문의
  if (mn < 1) mn = 1;               // 하한 1만원 클램프
  if (mn > mx) mn = mx;
  return { min: toWon(mn), max: toWon(mx) };
};

